const ALIAS_TO_CANONICAL = new Map();
COUNTRIES.forEach(([name, aliases]) => {
  ALIAS_TO_CANONICAL.set(name.toLowerCase(), name);
  aliases.forEach(a => ALIAS_TO_CANONICAL.set(a.toLowerCase(), name));
});

function normalizeCountry(raw) {
  const trimmed = String(raw || '').trim();
  if (!trimmed) return null;
  const key = trimmed.toLowerCase().replace(/[.,]/g, '');
  return ALIAS_TO_CANONICAL.get(key) || trimmed;
}

// The canonical list, for the leads page's country filter dropdown — every
// value normalizeCountry can produce from a recognized input, so the filter
// always has every "real" country available even before any lead uses it,
// alongside whatever unrecognized free-text values leads actually have.
const CANONICAL_COUNTRIES = COUNTRIES.map(([name]) => name);

module.exports = { normalizeCountry, CANONICAL_COUNTRIES };
